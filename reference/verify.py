def hull_faces(points):
    """Exact brute-force face lattice of the convex hull of a finite set of integer points that spans its space
    (dimension 3 or 4).  A facet is the set of points on a hyperplane through n affinely independent points that has
    every point on one side; every face is an intersection of facets.  Returns {dimension: set of faces as frozensets}."""
    n = len(points[0]); P = [tuple(p) for p in points]

    def det3(a, b, c):
        return a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0]) + a[2] * (b[0] * c[1] - b[1] * c[0])

    def normal(vs):                      # a covector vanishing on the n-1 difference vectors vs
        if n == 3:
            a, b = vs
            return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
        a, b, c = vs
        cols = lambda v, skip: tuple(v[k] for k in range(4) if k != skip)
        return tuple((-1) ** k * det3(cols(a, k), cols(b, k), cols(c, k)) for k in range(4))
    facets = set()
    for combo in combinations(range(len(P)), n):
        p0 = P[combo[0]]
        f = normal([tuple(P[k][t] - p0[t] for t in range(n)) for k in combo[1:]])
        if not any(f):
            continue
        c0 = sum(f[t] * p0[t] for t in range(n))
        vals = [sum(f[t] * q[t] for t in range(n)) - c0 for q in P]
        if all(v >= 0 for v in vals) or all(v <= 0 for v in vals):
            facets.add(frozenset(k for k, v in enumerate(vals) if v == 0))
    faces = set(facets); frontier = set(facets)
    while frontier:
        new = set()
        for a in frontier:
            for b in facets:
                c = a & b
                if c and c not in faces:
                    faces.add(c); new.add(c)
        frontier = new

    def dim(face):
        pts = [P[k] for k in face]; rows = [[Fr(q[t] - pts[0][t]) for t in range(n)] for q in pts[1:]]; rank = 0
        for col in range(n):
            piv = next((r for r in range(rank, len(rows)) if rows[r][col] != 0), None)
            if piv is None:
                continue
            rows[rank], rows[piv] = rows[piv], rows[rank]
            for r in range(len(rows)):
                if r != rank and rows[r][col] != 0:
                    fct = rows[r][col] / rows[rank][col]
                    rows[r] = [x - fct * y for x, y in zip(rows[r], rows[rank])]
            rank += 1
        return rank
    out = {}
    for face in faces:
        out.setdefault(dim(face), set()).add(face)
    return out, P



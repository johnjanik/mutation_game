def known(L, n):
    """Textbook values, typed in independently of the oracle."""
    if L == 'A':
        return dict(N=n * (n + 1) // 2, h=n + 1, W=factorial(n + 1), det=n + 1, theta=[1] * n,
                    exps=list(range(1, n + 1)), minuscule=list(range(1, n + 1)))
    if L == 'B':
        return dict(N=n * n, h=2 * n, W=2 ** n * factorial(n), det=2, theta=[1] + [2] * (n - 1),
                    theta_s=[1] * n, exps=list(range(1, 2 * n, 2)), minuscule=[n])
    if L == 'C':
        return dict(N=n * n, h=2 * n, W=2 ** n * factorial(n), det=2, theta=[2] * (n - 1) + [1],
                    theta_s=[1] + [2] * (n - 2) + [1], exps=list(range(1, 2 * n, 2)), minuscule=[1])
    if L == 'D':
        return dict(N=n * (n - 1), h=2 * n - 2, W=2 ** (n - 1) * factorial(n), det=4,
                    theta=[1] + [2] * (n - 3) + [1, 1], exps=sorted(list(range(1, 2 * n - 2, 2)) + [n - 1]),
                    minuscule=[1, n - 1, n])
    if (L, n) == ('E', 6):
        return dict(N=36, h=12, W=51840, det=3, theta=[1, 2, 2, 3, 2, 1], exps=[1, 4, 5, 7, 8, 11], minuscule=[1, 6])
    if (L, n) == ('E', 7):
        return dict(N=63, h=18, W=2903040, det=2, theta=[2, 2, 3, 4, 3, 2, 1], exps=[1, 5, 7, 9, 11, 13, 17], minuscule=[7])
    if (L, n) == ('E', 8):
        return dict(N=120, h=30, W=696729600, det=1, theta=[2, 3, 4, 6, 5, 4, 3, 2],
                    exps=[1, 7, 11, 13, 17, 19, 23, 29], minuscule=[])
    if (L, n) == ('F', 4):
        return dict(N=24, h=12, W=1152, det=1, theta=[2, 3, 4, 2], theta_s=[1, 2, 3, 2], exps=[1, 5, 7, 11], minuscule=[])
    if (L, n) == ('G', 2):
        return dict(N=6, h=6, W=12, det=1, theta=[3, 2], theta_s=[2, 1], exps=[1, 5], minuscule=[])
    raise KeyError((L, n))


def known_minus_w0(L, n):
    if L == 'A':
        return list(range(n, 0, -1))
    if L == 'D' and n % 2 == 1:
        return list(range(1, n - 1)) + [n, n - 1]
    if (L, n) == ('E', 6):
        return [6, 2, 5, 4, 3, 1]
    return list(range(1, n + 1))


def known_numbers_of_theta(L, n):
    """(numbers of the highest root, numbers of the highest short root or None), as {node: value} with zeros omitted."""
    if L == 'A':
        return ({1: 2} if n == 1 else {1: 1, n: 1}), None
    if L == 'B':
        return ({2: 2} if n == 2 else {2: 1}), {1: 1}
    if L == 'C':
        return {1: 2}, {2: 1}
    if L == 'D' or (L, n) == ('E', 6):
        return {2: 1}, None
    if (L, n) == ('E', 7):
        return {1: 1}, None
    if (L, n) == ('E', 8):
        return {8: 1}, None
    if (L, n) == ('F', 4):
        return {1: 1}, {4: 1}
    if (L, n) == ('G', 2):
        return {2: 1}, {1: 1}


def sparse(a):
    return {i + 1: x for i, x in enumerate(a) if x != 0}



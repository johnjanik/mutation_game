def syt_count(shape):
    """Number of standard Young tableaux of a partition shape, by the hook length formula."""
    cells = sum(shape); conj = [sum(1 for r in shape if r > c) for c in range(shape[0])]; hooks = 1
    for r, length in enumerate(shape):
        for c in range(length):
            hooks *= (length - c) + (conj[c] - r) - 1
    return factorial(cells) // hooks



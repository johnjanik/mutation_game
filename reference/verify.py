def golden_fold_search(C):
    """All ways to split the nodes into non-adjacent ordered pairs (plain, golden) such that acting on a pair is a
    Z[phi]-linear move on the vector of values plain + phi * golden."""
    n = len(C); m = n // 2

    def pairings(lst):
        if not lst:
            yield []; return
        a = lst[0]
        for k in range(1, len(lst)):
            b = lst[k]
            if C[a][b] != 0:
                continue
            for rest in pairings(lst[1:k] + lst[k + 1:]):
                yield [(a, b)] + rest
    found = []
    for pr in pairings(list(range(n))):
        for flips in product([0, 1], repeat=m):
            prs = [(b, a) if f else (a, b) for (a, b), f in zip(pr, flips)]
            proj = lambda p: tuple(Phi(p[a], p[b]) for (a, b) in prs)
            ok = True
            for j, (a, b) in enumerate(prs):
                row = []
                for (a2, b2) in prs:                       # image of the plain unit vector of each pair fixes the matrix row
                    img = proj(mutate(C, mutate(C, unit(n, a2), a), b))
                    row.append((Phi(1) if (a2, b2) == (a, b) else Phi(0)) - img[j])
                for t, (a2, b2) in enumerate(prs):         # the golden unit vector must then follow by linearity
                    img = proj(mutate(C, mutate(C, unit(n, b2), a), b))
                    ok &= img[j] == (PHI if t == j else Phi(0)) - row[t] * PHI
            if ok:
                found.append(frozenset((a + 1, b + 1) for a, b in prs))
    return found



    check(f'{label}: marks satisfy C.delta = 0, comarks are a left null vector, all entries positive',
          all(sum(Ca[i][j] * mk[j] for j in range(m)) == 0 for i in range(m)) and min(mk) > 0
          and all(sum(cmk[i] * Ca[i][j] for i in range(m)) == 0 for j in range(m)) and min(cmk) > 0)
    check(f'{label}: delta is fixed by every mutation', all(mutate(Ca, mk, i) == mk for i in range(m)))

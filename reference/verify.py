def cartan_involution_is_inner(C, X, tau):
    """Is theta = -w_X tau an element of the Weyl group?  Carry the base theta(simple roots) back to the simple roots
    by reflections (each step makes one more positive root positive again) and see whether what remains is the identity."""
    n = len(C); word = []
    def g_inverse(p):                      # g = s_{j_k} ... s_{j_1} theta, and theta is its own inverse
        for j in reversed(word):
            p = mutate(C, p, j)
        return theta(C, X, tau, p)
    for _ in range(len(roots(C)) // 2 + 1):
        j = next((k for k in range(n) if all(x <= 0 for x in g_inverse(unit(n, k)))), None)
        if j is None:
            break
        word.append(j)
    def g(p):
        p = theta(C, X, tau, p)
        for j in word:
            p = mutate(C, p, j)
        return p
    images = [g(unit(n, i)) for i in range(n)]
    assert sorted(images) == sorted(unit(n, i) for i in range(n))        # g permutes the simple roots
    return all(images[i] == unit(n, i) for i in range(n))
